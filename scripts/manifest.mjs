// Regenerates content-inbox/manifest.json: one record per source file, keyed by
// sha256. Run it after dropping anything into content-inbox.
//
//   node scripts/manifest.mjs
//
// manifest.json is GENERATED — don't hand-edit it. Provenance for files fetched
// automatically lives in PROVENANCE below; anything else is marked user-supplied.
// Extraction results (written later by the content pipeline) are carried across
// runs by sha256, so re-running never loses them and never duplicates a source.

