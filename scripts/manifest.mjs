const sha256 = (path) => new Promise((res, rej) => {
  const h = createHash('sha256');
  createReadStream(path).on('data', (d) => h.update(d)).on('end', () => res(h.digest('hex'))).on('error', rej);
});

async function* walk(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) yield* walk(p);
    else if (!SKIP.has(e.name)) yield p;
  }
}

// A missing manifest is the first run. A corrupt one must abort loudly: falling
// back to empty would silently discard every extraction record in it.
const raw = await readFile(MANIFEST, 'utf8').catch((err) => {
  if (err.code === 'ENOENT') return null;
  throw err;
});
let prev = { sources: [] };
if (raw !== null) {
  try {
    // Strip a UTF-8 BOM — PowerShell's `Set-Content -Encoding utf8` writes one
    // and JSON.parse rejects it.
    prev = JSON.parse(raw.replace(/^﻿/, ''));
  } catch (err) {
    throw new Error(`manifest.json exists but could not be parsed — refusing to overwrite it and lose extraction state.\n${err.message}`);
  }
}
const byHash = new Map(prev.sources.map((s) => [s.sha256, s]));

const sources = [];
for await (const path of walk(INBOX)) {
  const [hash, info] = await Promise.all([sha256(path), stat(path)]);
  const rel = relative(INBOX, path).split(sep).join('/');
  const name = rel.split('/').pop();
  const [source_url, licence, notes] = PROVENANCE[name] ?? [null, 'unknown — user supplied', ''];
  const old = byHash.get(hash);
  sources.push({
    path: rel,
    sha256: hash,
    bytes: info.size,
    added: old?.added ?? new Date().toISOString().slice(0, 10),
    source_url,
    licence,
    notes,
    // Carried across runs so re-importing never re-does work or loses corrections.
    extracted: old?.extracted ?? null,
  });
}
sources.sort((a, b) => a.path.localeCompare(b.path));

await writeFile(MANIFEST, JSON.stringify({ version: 1, generated: new Date().toISOString(), sources }, null, 2) + '\n');
const gb = sources.reduce((n, s) => n + s.bytes, 0) / 1e9;
console.log(`${sources.length} sources, ${gb.toFixed(2)} GB`);
console.log(`${sources.filter((s) => s.extracted).length} extracted, ${sources.filter((s) => !s.extracted).length} pending`);
const unknown = sources.filter((s) => !s.source_url);
if (unknown.length) console.log(`\nuser-supplied (no provenance recorded):\n${unknown.map((s) => '  ' + s.path).join('\n')}`);
